package com.dustikun.seckill.Common.constant;

/**
 * 待补偿任务的类型。
 * <p>
 * 三种补偿的语义完全不同，落表时必须分开存，否则定时任务重试时会用错动作把数据搞坏：
 * 一个会把用户从「已购」集合里摘掉（导致重复下单），一个必须把标记留着，
 * 还有一个必须先改数据库状态、确认订单不成立之后才敢动库存。
 */
public enum CompensateType {

    /**
     * 完整回滚：库存 +1 且摘掉用户已购标记。
     * <p>
     * 用于「这次下单根本不该成立」且「订单在数据库里也不该保留」的场景
     * （降级同步落库失败、消息投递重试耗尽且尚未落地订单）。
     */
    ROLLBACK_ALL,

    /**
     * 仅回补库存：库存 +1，<b>保留</b>用户已购标记。
     * <p>
     * 用于「订单确实成立（或确实被取消）但预扣是多余的」——例如落库撞 uk_user_stock，
     * 或消费端重试耗尽取消订单后的归还。
     * 标记必须保留，否则用户在 Redis 侧会被重新放行，陷入
     * 「放行 → DB 拦截 → 回补 → 再放行」的死循环。
     */
    RESTORE_STOCK_ONLY,

    /**
     * 取消订单并归还预扣：<b>先</b>把订单从 PENDING 置为 CANCELLED，<b>确认之后才</b>归还库存。
     * <p>
     * 用于「消费端重试耗尽、但取消订单这一步本身失败了」的场景。
     * 它不能退化成 {@link #RESTORE_STOCK_ONLY}：订单若仍是 PENDING，
     * 重投依然可能拿到许可证并真实扣减库存，那时库存已被归还 → 超卖。
     * 所以这两步必须捆绑成同一个动作，且顺序不可颠倒。
     */
    CANCEL_ORDER
}
