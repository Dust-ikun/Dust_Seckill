--[[
  对账校准：只在「读到的值没变」时才写入（值比对，防止覆盖并发预扣）

  为什么不能直接用 SET：
    对账的读与写无法原子 —— 读完 Redis、写回之前，若有请求完成了预扣，
    这次 SET 会把那次预扣直接抹掉：Redis 凭空多出一件可售，而订单已经落库，
    随后数据库的条件扣减会兜住（用户看到「抢到了却下单失败」，补偿链路再兜一圈）。
    这里把「读到的值」当作乐观锁版本号：值一变就放弃本次校准。
    宁可这一轮不修（下一轮会基于新值重新判定），也不覆盖别人的写入。

  KEYS[1] = 库存 key   seckill:stock:{stockId}
  ARGV[1] = 校准前读到的值（原样字符串比较）
  ARGV[2] = 要写入的新值

  ---------------------------- 返回码 ----------------------------
    1  : 校准成功
    0  : 值已变（期间有并发预扣 / 归还），本次未修改任何数据
   -1  : 库存 key 不存在（活动已清理），本次未修改任何数据

  ------------------------- 设计要点 -------------------------
  · 值比较是字符串比较。库内值由本项目的 Lua（SET / INCRBY）写入，永远是规范十进制，
    所以「读到的整数 → 字符串」与原值一致；若有人手工写入 " 99" 这类
    非规范值，比较会不等 → 放弃校准（安全方向）。
  · 该比较挡不住 ABA（先扣 1 再补 1，值回到原样）。这种形状要求「一次预扣与一次归还在
    读与写之间同时完成」，而归还本身受一次性去重键保护，实际不会发生；如实记在这里。
  · 本脚本只碰一个 key，不涉及集群同 slot 约束（其它脚本的 {stockId} hash tag 约定不受影响）。
--]]

local stockKey = KEYS[1]
local expected = ARGV[1]
local target   = ARGV[2]

local current = redis.call('GET', stockKey)
if not current then
    return -1
end

-- 值已变 = 有人在这中间改过库存（预扣或归还），本次没有资格改写
if current ~= expected then
    return 0
end

redis.call('SET', stockKey, target)
return 1
