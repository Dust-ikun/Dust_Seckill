--[[
  库存回补脚本（区分返回码 + 幂等保护）

  补偿场景：Redis 预扣成功，但后续数据库落库失败（事务回滚 / 连接中断 / 消费重试耗尽），
  必须把 Redis 侧的库存和用户预扣标记一起还原，否则这部分库存会永久丢失（少卖）。

  KEYS[1] = 库存 key          seckill:stock:{stockId}
  KEYS[2] = 已购用户集合 key  seckill:bought:{stockId}
  ARGV[1] = userId
  ARGV[2] = 回补数量

  ---------------------------- 返回码 ----------------------------
    >= 0 : 回补成功，返回值为回补后的剩余库存
    -1   : 入参非法（回补数量 <= 0），拒绝执行
    -2   : 库存 key 不存在（活动已结束或缓存已清理），本次未修改任何数据
    -3   : 用户预扣标记不存在，说明此前已回补过；本次未修改任何数据（幂等命中）

  ------------------------- 设计要点 -------------------------
  「入参非法」「活动已结束」「脚本没返回结果」是三种完全不同的结局，
  不能挤在同一个返回码上，否则调用方根本无法区分。

  回补必须幂等：不加保护的话，重复调用会把库存 INCRBY 多次，导致库存虚增（进而超卖）。

  因此本脚本先用 SREM 的返回值判断「这个标记是不是本次调用摘掉的」：
  只有确实摘掉标记的那一次调用才有资格回补库存，其余调用一律返回 -3 且不改动任何数据。
--]]

local stockKey  = KEYS[1]
local boughtKey = KEYS[2]
local userId    = ARGV[1]
local num       = tonumber(ARGV[2])

-- 入参校验：回补数量必须为正，否则坚决不动库存
if num == nil or num <= 0 then
    return -1
end

-- 活动已结束 / 缓存已清理：库存 key 都不存在了，没有任何东西需要还原。
-- 这里刻意不执行 SREM，让这个分支保持「纯只读」，语义最干净：
-- 返回 -2 就意味着「本次调用没有修改任何数据」。
if redis.call('EXISTS', stockKey) == 0 then
    return -2
end

-- 幂等保护（本版本的关键修复）：
-- SREM 返回 1 表示标记确实由本次调用摘掉，才有权把库存加回去；
-- 返回 0 表示标记早已不在（此前已回补过，或该用户从未预扣成功），
-- 此时若仍执行 INCRBY 就会把库存越补越多，造成库存虚增。
if redis.call('SREM', boughtKey, userId) == 0 then
    return -3
end

local remain = redis.call('INCRBY', stockKey, num)
return remain
